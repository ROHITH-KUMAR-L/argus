"""Generate docs/test_matrix.md: every test-catalogue ID → tests that exercise it.

IDs are found by scanning test sources (Rust and Python) for the catalogue
pattern, so the matrix reflects the code, not intentions. IDs with no test are
listed with their documented status instead of being omitted.
"""

from __future__ import annotations

import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ID = re.compile(r"\b(POL|RAT|AGT|LL|SEC|SUB|DKR|RES|AUD|LEG|EVA|FAIL|PERF|STK)-(\d{3})[a-z]?\b")
# Test function names: test_rat_010_to_013_x, fn ll_003_004_005_x, test_aud_001_008_x
DEF = re.compile(r"(?:def |fn )([a-z0-9_]+)\(")
FN = re.compile(
    r"(pol|rat|agt|ll|sec|sub|dkr|res|aud|leg|eva|fail|perf|stk)"
    r"_(\d{3}(?:_\d{3})*(?:_to_\d{3})?)(?![0-9])",
    re.I,
)


def expand(prefix: str, nums: str) -> list[str]:
    parts = nums.split("_")
    if "to" in parts:
        lo, hi = int(parts[0]), int(parts[-1])
        vals = list(range(lo, hi + 1))
    else:
        vals = [int(x) for x in parts]
    return [f"{prefix.upper()}-{v:03d}" for v in vals]


SOURCES = [
    *ROOT.glob("tests/**/*.py"),
    *ROOT.glob("crates/*/tests/*.rs"),
    *ROOT.glob("crates/*/src/**/*.rs"),
    *ROOT.glob("evaluation/*.py"),
    *ROOT.glob("evaluation/scenarios/*.json"),
    *ROOT.glob("tests/fixtures/*.json"),
]
EVIDENCE_DOCS = {"evaluation/perf.py": "measured in perf.json/perf.md"}
STATUS_NOTES = {
    "DKR-015": "UNSUPPORTED on the reference host (rootful Docker); test present and skips",
    "LL-017": "kernel run UNSUPPORTED (single kernel); planning logic unit-tested",
    "LL-016": "DOCUMENTED behaviour (docs/confinement.md)",
    "RES-009": "covered by AUD-013 fail-closed writer test (disk-full is an OSError path)",
    "RES-011": "no concurrency cap is implemented; concurrent isolation covered by SUB-016/PERF-010",
    "RES-013": "covered by RAT-018/019 (restart, corruption); no VM reboot test",
    "SEC-019": "python-strict-v1 default-deny profile",
    "POL-010": "lexical layer in policy-validator; kernel-level symlink denial is LL-012",
    "FAIL-004": "same fault injection as SEC-017 (seccomp filter load failure)",
    **{
        f"EVA-{n:03d}": "measured by the evaluation batch (evaluation/results/*/runs.jsonl, metrics.json)"
        for n in (2, 3, 4, 7, 8, 9)
    },
}


def catalogue() -> list[str]:
    text = (ROOT / "docs/test_criteria.md").read_text()
    return sorted(
        {f"{a}-{b}" for a, b in ID.findall(text)},
        key=lambda s: (s.split("-")[0], int(s.split("-")[1])),
    )


def main() -> None:
    hits: dict[str, set[str]] = defaultdict(set)
    for f in SOURCES:
        rel = f.relative_to(ROOT).as_posix()
        for line in f.read_text(errors="replace").splitlines():
            for a, b in ID.findall(line):
                hits[f"{a}-{b}"].add(rel)
            for d in DEF.finditer(line):
                for m in FN.finditer(d.group(1)):
                    for i_ in expand(m.group(1), m.group(2)):
                        hits[i_].add(rel)
    ids = catalogue()
    covered = [i for i in ids if i in hits]
    L = [
        "# Test traceability matrix",
        "",
        "Generated by `scripts/test_matrix.py` from the test sources; do not edit by hand.",
        "",
        f"Catalogue IDs: **{len(ids)}** · referenced by tests/harness: **{len(covered)}** · "
        f"not referenced: **{len(ids) - len(covered)}**",
        "",
        "| ID | Where | Note |",
        "|---|---|---|",
    ]
    for i in ids:
        where = ", ".join(f"`{p}`" for p in sorted(hits.get(i, ()))) or "—"
        L.append(f"| {i} | {where} | {STATUS_NOTES.get(i, '')} |")
    (ROOT / "docs/test_matrix.md").write_text("\n".join(L) + "\n")
    missing = [i for i in ids if i not in hits and i not in STATUS_NOTES]
    print(f"{len(covered)}/{len(ids)} referenced; unreferenced without a note: {missing}")


if __name__ == "__main__":
    main()
