"""Markdown comparison report generated from metrics.json and runs.jsonl only."""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path
from typing import Any

ARMS = ("B0", "B1", "P1")


def _r(x: dict[str, Any] | None) -> str:
    if not x or x.get("denominator") in (None, 0):
        return "n/a"
    ci = x.get("ci95")
    ci_s = f" [{ci[0]:.2f}, {ci[1]:.2f}]" if ci else ""
    return f"{x['numerator']}/{x['denominator']} = {x['rate']:.2f}{ci_s}"


def write(out: Path, m: dict[str, Any]) -> Path:
    runs = [json.loads(x) for x in (out / "runs.jsonl").read_text().splitlines()]
    env = json.loads((out / "environment.json").read_text())
    L: list[str] = [
        "# Argus evaluation report",
        "",
        f"Batch `{out.name}` · kernel {env['kernel']} · Docker {env['docker']} · "
        f"image `{env['image_id'][:19]}…`",
        "",
        "Generated by `evaluation/report.py` from `runs.jsonl` and `metrics.json`; "
        "every number below is recomputable from those files.",
        "",
        f"Runs: {m['runs']['scheduled']} scheduled, {m['runs']['scored']} scored, "
        f"{m['runs']['invalid']} invalid ({', '.join(m['runs']['invalid_reasons']) or 'none'}).",
        "",
        "## Security and utility by arm",
        "",
        "| Metric | B0 (isolated, ungated) | B1 (static sandbox) | P1 (proposed) |",
        "|---|---|---|---|",
    ]
    a = m["arms"]

    def row(label: str, key: str) -> None:
        L.append(f"| {label} | " + " | ".join(_r(a.get(arm, {}).get(key)) for arm in ARMS) + " |")

    row("Attack success rate (effects / valid attempts)", "attack_success_rate")
    for cat in ("prompt_injection", "staged_escalation", "subprocess_misuse"):
        L.append(
            f"| — {cat} | "
            + " | ".join(
                _r(a.get(arm, {}).get("attack_success_by_category", {}).get(cat)) for arm in ARMS
            )
            + " |"
        )
    L.append(
        "| Policy-gate denials in attacks | "
        + " | ".join(str(a.get(arm, {}).get("attack_policy_denials", "n/a")) for arm in ARMS)
        + " |"
    )
    L.append(
        "| In-worker denials in attacks (Landlock/seccomp; in B0 only Docker's default profile) | "
        + " | ".join(str(a.get(arm, {}).get("attack_kernel_denials", "n/a")) for arm in ARMS)
        + " |"
    )
    row("Legitimate task completion (independently verified)", "legit_task_completion_rate")
    row("False-denial rate (legit denials / legit actions)", "false_denial_rate")
    row("Step-up requested when policy too narrow (LEG-015)", "stepup_requested_rate")
    L.append(
        "| Narrowing transitions applied / attempted | "
        + " | ".join(
            "{applied}/{attempted}".format(**a[arm]["narrowing_transitions"]) if arm in a else "n/a"
            for arm in ARMS
        )
        + " |"
    )
    c = m["comparisons"]
    L += [
        "",
        "## Comparisons",
        "",
        f"- ASR reduction, P1 vs B0: **{c['asr_reduction_P1_vs_B0']}**",
        "- Staged-escalation effects (ratchet-specific): "
        + ", ".join(f"{arm} {_r(v)}" for arm, v in c["staged_escalation_effects"].items()),
        f"- Median end-to-end latency overhead on legitimate scenarios: P1 vs B0 "
        f"{c['latency_overhead_P1_vs_B0']['median_overhead']}, P1 vs B1 "
        f"{c['latency_overhead_P1_vs_B1']['median_overhead']}; p95 vs B0 "
        f"{c['latency_overhead_P1_vs_B0']['p95_overhead']}",
        f"- Utility retention (LTCR P1 − B0): {c['utility_retention_pp']} percentage points",
        f"- Reproducibility: {m['reproducibility']['groups']} scenario×arm groups, "
        f"{len(m['reproducibility']['unstable'])} unstable",
        "",
        "## Proposed targets (success_criteria.md)",
        "",
        "| Target | Met |",
        "|---|---|",
    ]
    for k, v in m["targets"].items():
        L.append(f"| {k} | {'yes' if v is True else 'NO' if v is False else 'n/a'} |")

    L += [
        "",
        "## Per-scenario outcomes",
        "",
        "Effect = unauthorized effect completed in any repetition (attacks); "
        "OK = independently verified success (legitimate). Cells show k/n over repetitions.",
        "",
        "| Scenario | Category | B0 | B1 | P1 |",
        "|---|---|---|---|---|",
    ]
    cells: dict[tuple[str, str], list[dict[str, Any]]] = defaultdict(list)
    for r in runs:
        if r["status"] == "SCORED":
            cells[(r["scenario_id"], r["arm"])].append(r)
    for sid in sorted({r["scenario_id"] for r in runs}):
        cat = next(r["category"] for r in runs if r["scenario_id"] == sid)
        vals = []
        for arm in ARMS:
            rs = cells.get((sid, arm), [])
            if not rs:
                vals.append("n/a")
            elif cat == "legitimate":
                vals.append(f"OK {sum(bool(r['legit_success']) for r in rs)}/{len(rs)}")
            else:
                vals.append(
                    f"effect {sum(bool(r['unauthorized_effect_completed']) for r in rs)}/{len(rs)}"
                )
        L.append(f"| {sid} | {cat} | " + " | ".join(vals) + " |")

    L += [
        "",
        "## Provenance (EVA-013)",
        "",
        "Each row of `runs.jsonl` holds `run_id`, `run_dir`, policy hash, image digest, kernel, "
        "fixture hash and `evidence` (event IDs in that run's hash-chained `events.jsonl`).",
        "",
        "| Scenario | Arm | Rep | Run | Outcome | Evidence (first) |",
        "|---|---|---|---|---|---|",
    ]
    for r in runs[:60]:
        if r["status"] == "SCORED":
            L.append(
                f"| {r['scenario_id']} | {r['arm']} | {r['rep']} | `{r['run_id']}` | "
                f"{r['outcome']} | {(r['evidence'] or ['-'])[0]} |"
            )
    L += [
        "",
        "## Threats to validity",
        "",
        "- Attack behaviour is scripted (deterministic mock planner, worst-case obedient agent). "
        "This measures containment, not how often a real model would attempt attacks.",
        "- Network attacks are not in the corpus: every arm runs with `--network none`, so they "
        "cannot discriminate between arms on this setup.",
        "- B0 keeps Docker's outer protections (default seccomp, no capabilities, read-only root), "
        "so some attacks are blocked even in B0; the per-layer counts show which layer acted.",
        "- One host and kernel (see environment); results do not generalize beyond it.",
        "- Latency includes per-action container start-up, which dominates; small per-run "
        "differences are within noise at this repetition count.",
    ]
    path = out / "report.md"
    path.write_text("\n".join(L) + "\n")
    return path
